import type { Sql } from 'postgres'
import type { CliDeps, CliIO } from '../cli'
import { loadConfig, type RedrowConfig } from '../config'
import { assertAllowedTarget, describeDbError, type ConnectionTarget } from '../connection'
import { CliError } from '../errors'
import { EXIT_FINDINGS, EXIT_OK, exitCodeFor } from '../exit-codes'
import { AiError, DEFAULT_MODEL, type GeneratedText } from '../fix/ai'
import { MigrationError, parseMigration, parseModelOutput, type Migration } from '../fix/migration'
import { buildFixPrompt, type FixPrompt } from '../fix/prompt'
import { loadReport } from '../fix/report-file'
