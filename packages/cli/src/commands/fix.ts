export interface FixFlags {
  readonly from: string
  readonly db?: string
  readonly config?: string
  readonly apply?: boolean
  readonly out?: string
  readonly iKnowWhatImDoing?: boolean
}

export interface FixDeps {
  readonly introspect: (
    sql: Sql,
    schemas: readonly string[],
    ownerColumns: Readonly<Record<string, string>>,
  ) => Promise<Introspection>
  readonly validate: (sql: Sql, statements: readonly string[]) => Promise<void>
  readonly apply: (sql: Sql, statements: readonly string[]) => Promise<void>
  readonly generate: (prompt: FixPrompt, apiKey: string, model: string) => Promise<GeneratedText>
}

const AI_ATTEMPTS = 2

interface FixRun {
  readonly report: Report
  readonly catalog: Introspection
  readonly sql: Sql
  readonly io: CliIO
  readonly fix: FixDeps
  readonly target: ConnectionTarget
}

const warn = (io: CliIO, text: string): void => io.stderr(`Warning: ${sanitizeForTerminal(text)}\n`)

/** The reason to show, and to tell the model. Never a raw SDK error, which could carry anything. */
function reasonFor(error: unknown, target: ConnectionTarget): string {
  if (error instanceof AiError || error instanceof MigrationError) return error.message
  return describeDbError(error, target)
}

/** Who wrote this, at the top of the file. Added after parsing, and always one sanitized line. */
function withModelHeader(migration: Migration, generated: GeneratedText, requested: string): Migration {
  const answered = sanitizeForTerminal(generated.model)
  const written = generated.usedFallback
    ? `-- Written by ${answered}, because ${sanitizeForTerminal(requested)} declined this request (server-side fallback).`
    : `-- Written by ${answered}.`
  return { ...migration, text: `${written}\n${migration.text}` }
}

/** One model attempt: parsed and run in a rolled-back transaction, or it throws. */
async function tryModel(run: FixRun, prompt: FixPrompt, apiKey: string, model: string): Promise<Migration> {
  let generated: GeneratedText
  try {
    generated = await run.fix.generate(prompt, apiKey, model)
  } catch (error: unknown) {
    throw error instanceof AiError ? error : new AiError('the API call failed')
  }
  const migration = parseModelOutput(generated.text)
  assertInScope(migration.statements, run.report, run.catalog)
  await run.fix.validate(run.sql, migration.statements)
  const answered = sanitizeForTerminal(generated.model)
  if (generated.usedFallback) run.io.stderr(`Note: ${sanitizeForTerminal(model)} declined this request, so ${answered} wrote it.\n`)
  run.io.stderr(`Generated by ${answered}, and checked in a transaction that was rolled back.\n`)
  return withModelHeader(migration, generated, model)
}

/** Returns a checked migration from the model, or undefined so the caller can use templates. */
async function generateWithModel(run: FixRun, apiKey: string, model: string): Promise<Migration | undefined> {
  const prompt = buildFixPrompt(run.report, run.catalog)
  let reason = ''
  for (let attempt = 1; attempt <= AI_ATTEMPTS; attempt += 1) {
    const attemptPrompt =
      attempt === 1
        ? prompt
        : { ...prompt, user: `${prompt.user}\n\nYour previous migration was rejected: ${reason}\nWrite it again.` }
    try {
      return await tryModel(run, attemptPrompt, apiKey, model)
    } catch (error: unknown) {
      reason = reasonFor(error, run.target)
      if (error instanceof AiError) break
    }
  }
  warn(run.io, `${model} could not produce a usable migration (${reason}). Using rule-based templates instead.`)
  return undefined
}

async function templateMigration(run: FixRun): Promise<Migration | undefined> {
  const planned = buildTemplateMigration(run.report, run.catalog)
  for (const note of planned.manual) run.io.stderr(`Needs a person: ${note}\n`)
  if (planned.statementCount === 0) return undefined
  const migration = parseMigration(planned.text)
  await run.fix.validate(run.sql, migration.statements)
  run.io.stderr('Generated from rule-based templates, and checked in a transaction that was rolled back.\n')
  return migration
}

function writeMigration(migration: Migration, flags: FixFlags, io: CliIO): void {
  const name = flags.out ?? `redrow-fix-${new Date().toISOString().replace(/[:.]/g, '-')}.sql`
  try {
    writeFileSync(resolve(io.cwd, name), migration.text)
  } catch {
    throw new CliError(`Could not write ${name}`)
  }
  io.stdout(`Wrote ${sanitizeForTerminal(name)}\n`)
}

function assertSameDatabase(report: Report, target: ConnectionTarget): void {
  if (report.database.host === target.host && report.database.name === target.database) return
  throw new CliError(
    `This report is from a different database (${report.database.host}/${report.database.name}), not ${target.label}. ` +
      'Scan this database first, so the fix matches what is really there.',
  )
}

const scoreOf = (score: number, grade: string): string => `${score}/100 (${grade})`

async function applyAndRescan(run: FixRun, migration: Migration, config: RedrowConfig, deps: CliDeps): Promise<ScanResult> {
  await run.fix.apply(run.sql, migration.statements)
  const options = toScanOptions({ severity: 'low', color: false }, config, run.target)
  const after = await deps.scan(run.sql, { ...options, schemas: run.report.database.schemas })
  const before = run.report.summary
  run.io.stdout(`Score ${scoreOf(before.score, before.grade)} → ${scoreOf(after.score, after.grade)}\n`)
  for (const finding of after.findings.filter((f) => f.severity !== 'info')) {
    run.io.stderr(`Still open: ${finding.ruleId} ${sanitizeForTerminal(finding.table ?? finding.schema)}: ${sanitizeForTerminal(finding.title)}\n`)
  }
  return after
}

async function confirmApply(migration: Migration, flags: FixFlags, run: FixRun): Promise<boolean> {
  if (flags.iKnowWhatImDoing === true) return true
  const count = migration.statements.length
  const name = sanitizeForTerminal(run.target.label)
  return (await run.io.confirm?.(`Apply ${count} statements to ${name}? This commits them. [y/N] `)) === true
}

async function runWithConnection(run: FixRun, flags: FixFlags, config: RedrowConfig, deps: CliDeps): Promise<number> {
  const apiKey = run.io.env.ANTHROPIC_API_KEY
  const model = run.io.env.REDROW_MODEL || DEFAULT_MODEL
  if (!apiKey) run.io.stderr('No ANTHROPIC_API_KEY, so using rule-based templates.\n')
  const fromModel = apiKey ? await generateWithModel(run, apiKey, model) : undefined
  const migration = fromModel ?? (await templateMigration(run))
  if (migration === undefined) {
    run.io.stderr('No automatic fix is possible for these findings.\n')
    return EXIT_FINDINGS
  }
  writeMigration(migration, flags, run.io)
  if (flags.apply !== true) return EXIT_OK
  if (!(await confirmApply(migration, flags, run))) {
    run.io.stdout('Not applied. The migration is in the file above.\n')
    return EXIT_OK
  }
  const after = await applyAndRescan(run, migration, config, deps)
  return exitCodeFor(after.findings, 'low')
}

export async function runFix(flags: FixFlags, io: CliIO, deps: CliDeps): Promise<number> {
  if (flags.apply === true && flags.iKnowWhatImDoing !== true && io.confirm === undefined) {
    throw new CliError('--apply asks for confirmation, and there is no terminal to ask on. Pass -y to skip the question.')
  }
  const report = loadReport(flags.from, io.cwd)
  if (report.findings.every((f) => f.severity === 'info')) {
    io.stdout('Nothing to fix.\n')
    return EXIT_OK
  }
  const target = resolveTarget(flags, io)
  const config = loadConfig(flags.config, io.cwd)
  assertAllowedTarget(target, flags.iKnowWhatImDoing ?? false, config.allowHosts)
  assertSameDatabase(report, target)
  const fix = deps.fix
  if (fix === undefined) throw new CliError('redrow fix is not available in this build')
  const connection = deps.connect(target)
  try {
    const catalog = await fix.introspect(connection.sql, report.database.schemas, config.ownerColumns)
    return await runWithConnection({ report, catalog, sql: connection.sql, io, fix, target }, flags, config, deps)
  } catch (error: unknown) {
    throw error instanceof CliError ? error : new CliError(describeDbError(error, target))
  } finally {
    await connection.end()
  }
}
